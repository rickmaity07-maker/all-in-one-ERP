// Release signing: keystore.properties next to this project (local builds, git-ignored) or
// ANDROID_KEYSTORE_* environment variables (GitHub Actions). Updates must use the same key.
val keystoreProperties = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signingValue(key: String, env: String): String? = keystoreProperties.getProperty(key) ?: System.getenv(env)

